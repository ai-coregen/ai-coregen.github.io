/**
 * メインキャッチの1行に効かせる「折ってはいけない語句」を返す（`JaText` の `keep` に渡す）。
 *
 * **ヒーローのh1とトップLPの業種カードが同じ関数を通る**＝どちらか一方だけ折り位置が崩れる、
 * という事故が起きない（カードは幅が狭いので、実際に割れるのはたいていカードの側）。
 *
 * `mainCatch` が複数行の業種では語句が別の行に属するので、**その行に含まれる語句だけ**を渡す。
 * どの行にも無い語句は**表記ミス**とみなしてビルドを止める（黙って効かないと、崩れた折り返しが
 * そのまま本番に出る）。
 */
/**
 * 折ってはいけない語句のうち、**いちばん長いものの文字数**を返す（半角は0.5字として数える）。
 *
 * 保護語は幅が足りなくても割れてはいけないが、`overflow-wrap: anywhere` は
 * **入りきらなければ任意位置で折る**ので、CSS側で「保護語が収まる大きさ」に字を抑える必要がある。
 * その上限を出すのに使う（`--catch-len`）。**業種ごとに保護語の長さが違うので、
 * ブレークポイントを業種ごとに調整するのではなく、長さを渡して式で決める。**
 *
 * 保護語を持たない業種は `0` を返す（＝上限を効かせない）。
 */
export function mainCatchKeepLength(hero: IndustryHero): number {
  const keep = hero.mainCatchKeep ?? [];
  let longest = 0;
  for (const phrase of keep) {
    let width = 0;
    for (const ch of phrase) {
      /* 半角英数記号は約0.5字ぶんの幅（`AIで自動化` の `AI` など） */
      width += /[ -~｡-ﾟ]/.test(ch) ? 0.5 : 1;
    }
    longest = Math.max(longest, width);
  }
  return longest;
}

export function mainCatchKeepFor(hero: IndustryHero, line: string): string[] {
  const keep = hero.mainCatchKeep ?? [];
  for (const phrase of keep) {
    if (!hero.mainCatch.some((l) => l.includes(phrase))) {
      throw new Error(
        `mainCatchKeep の「${phrase}」が mainCatch のどの行にも含まれていません` +
          `（${JSON.stringify(hero.mainCatch)}）。正本の表記に揃えてください。`
      );
    }
  }
  return keep.filter((phrase) => line.includes(phrase));
}

