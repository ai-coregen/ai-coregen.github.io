// 業種別LPのテキスト定義（19業種を同じ形で並べる）。
//
// 【正本】各業種のコピーの正本は knowledge/industry-copy/{slug}.md。
//         このファイルはそれを実装用に構造化しただけのもので、文言は一字一句同じにする。
// 【文体】knowledge/manuals/tone-manner.md。業種別LPは英語アイブロウを使わない・
//         見出しや箇条書きに句点を付けない・カード内は体言止め、などトップLPの流儀に合わせる。
// 【構成】knowledge/lp-structure-research.md の承認済み11セクション。
//         hero / challenges / education / solution / transparency / after /
//         process / profile（トップの ProfileSection を再利用）/ midCta / faq / finalCta
// 【追加手順】knowledge/manuals/coding-manual.md を参照。

/** 段落＝原稿の1行を1要素にした配列。改行位置を原稿どおりに保つ（端末幅ではbudouxが更に折る） */
export type Paragraph = string[];

/** 見出しは意味の切れ目で割った行の配列。1行10〜20字（上限24字） */
export type Heading = string[];

export interface IndustryMeta {
  /** <title> */
  title: string;
  /** meta description */
  description: string;
  /** OGP画像に焼くテキスト（ページには描画しない） */
  ogpLines: string[];
}

/**
 * セクションに添える画像。
 * ファイルは public/industry/ に置く（命名は {slug}-{セクション}.webp）。
 * side は本文から見た画像の位置。ページ全体で 右→左→右→左 と交互にする。
 * **ファイルがまだ無いときは画像なしで描画される**（ビルド時に存在を確認する）。
 */
export interface SectionImage {
  file: string;
  alt: string;
  side: "left" | "right";
}

export interface IndustryHero {
  /**
   * メインキャッチ。改行位置は演出そのもの。
   * budouxやレスポンシブの都合で行を結合させない（1行=1ブロック要素で描画する）。
   */
  mainCatch: Heading;
  /** メインキャッチ直下の1行。「誰向け・何をするか」を引き取る */
  subCatch: string;
  /** 説明文 */
  subCopy: Paragraph[];
  primaryCta: string;
  secondaryCta: string;
  microCopy: string[];
  image: { file: string; alt: string; flip: boolean };
}

export interface IndustryChallenges {
  heading: Heading;
  checklist: string[];
  closing: Paragraph;
  emphasis: string[];
  image?: SectionImage;
}

export interface IndustryEducation {
  heading: Heading;
  body: Paragraph[];
  subHeading: Heading;
  subBody: Paragraph[];
  /** 統計の出典注記。削らない（数値の帰属を誤読させないための記載） */
  note: string;
  emphasis: string[];
  image?: SectionImage;
}

export interface Deliverable {
  title: string;
  /** 体言止め・句点なし・1行に収まる長さ */
  body: string;
}

/** 現行業務フロー図の1工程 */
export interface SampleFlowStep {
  /** 担当（例「営業事務」「見積担当」「社長」「誰も」）。工程箱の上に小さく出す */
  owner: string;
  /** 工程名 */
  title: string;
  /**
   * 工程に添える1行（例「FAX・メール」「着手できずに滞留」「人の判断」）。省略可。
   *
   * **所要時間の数値は入れない**（2026-08-11 判定・全業種共通）。
   * 見本画像には「15分／件」「平均2日」等が入っているが、①測定条件のない時短数字は禁止
   * ②業種研究に無い数字は書かない ③8/6に「測る数字」ブロックを全業種から削除した決定と
   * 矛盾する、の3点で全て外して定性表現に置き換えてある。
   * 「時間が溶けている」ことは `hot` のオレンジ枠と凡例だけで言い切れる。
   */
  note?: string;
  /**
   * true = 時間が溶けている工程（AI化の対象候補）。オレンジ枠＋淡いオレンジ地で描く。
   * **どの工程をhotにするかは正本（industry-copy）の指定に従う**。実装側で増やさない。
   */
  hot?: boolean;
}

/**
 * 納品物「現行業務フロー図」のサンプル図（セクション4・納品物リストの直後に**1枚だけ**置く）。
 *
 * 役割は「1枚にまとめます」を実物で見せること。**6項目すべての見本は作らない**
 * （枚数が増えると納品物リスト自体が読まれなくなる。正本 §4）。
 *
 * **SAMPLEバッジの文字はデータに持たない**（装飾記号をデータに入れないのと同じ理由で
 * 描画側の固定文字列にしてある）。
 */
export interface IndustrySampleFlow {
  /** 図タイトル（例「現行業務フロー図」）。納品物1の名前と一致させる */
  title: string;
  /** タイトル下の1行 */
  subtitle: string;
  /** 図の右下に小さく置く添え書き */
  credit: string;
  steps: SampleFlowStep[];
  /** 下の黒帯。1行目（太字） */
  summaryTitle: string;
  /** 下の黒帯。2行目 */
  summaryBody: string;
  /** 凡例。オレンジ枠の意味 */
  legendHot: string;
  /** 凡例。黒枠の意味 */
  legendNormal: string;
}

export interface IndustrySolution {
  heading: Heading;
  body: Paragraph[];
  deliverablesHeading: string;
  /** グリッドの枠が埋まる数にする（3列なら3・6・9個） */
  deliverables: Deliverable[];
  /**
   * 納品物のサンプル図（現行業務フロー図）。
   * **省略可**＝正本が着地していない業種はサンプル図なしで描画される。
   */
  sampleFlow?: IndustrySampleFlow;
  emphasis: string[];
  image?: SectionImage;
}

export interface FlowRow {
  label: string;
  body: string;
}

/**
 * 役割設計図の1列。
 * 入力・出力は黒箱の中に項目を並べ、AI・人は枠の中に箱を並べる（描画側が出し分ける）。
 */
export interface RoleMapColumn {
  /** 列の見出し（8字以内）。入力・出力は箱の中、AI・人は枠の上辺に出る */
  label: string;
  /** 項目（12字以内。長い1つだけ2行に折れてよい） */
  items: string[];
}

/** 図の下段に置くブロック（例外時の戻し先／最終承認） */
export interface RoleMapNote {
  /** 見出し6字以内 */
  title: string;
  /** 説明32字以内 */
  body: string;
}

/**
 * 5「AIがやること、人が決めること」の役割設計図（正本 §5・2026-08-11）。
 *
 * v3までは処理表（工程／内容の4行）だった。**表のままだと「AIが行う処理」と
 * 「人が決めること」が上下に積まれ、どちらが先でどこで人が止められるのかが読めない**ため
 * 図に置き換えた。見本は `knowledge/reference/rolemap-sample.jpg`。
 * **中身は処理表の項目を置き直しただけで、新しい約束は足していない。**
 *
 * **図タイトル・SAMPLEバッジ・「御社版を作成します」の添え書きは付けない**（正本 §5）。
 * h2が図タイトルの役割を果たしており、この図は納品物の見本ではなく提供内容そのものの説明なので、
 * 見本として見せるのはセクション4の現行業務フロー図1枚だけにする。
 */
export interface IndustryRoleMap {
  input: RoleMapColumn;
  ai: RoleMapColumn;
  human: RoleMapColumn;
  output: RoleMapColumn;
  /** 下段左（オレンジ破線枠）。AIの枠から破線矢印でつなぐ */
  fallback: RoleMapNote;
  /** 下段右（黒箱） */
  approval: RoleMapNote;
  /** 図の最下部に置く締め文。図の一部として図の中に置く */
  closing: string;
}

export interface IndustryTransparency {
  heading: Heading;
  lead: Paragraph;
  /**
   * 役割設計図。**省略可**＝正本が着地していない業種は下の処理表で描画される。
   * 全業種に行き渡ったら `flowHeader` / `flow` とテーブル描画は消す。
   */
  roleMap?: IndustryRoleMap;
  /** PCは2列表（工程列は中央寄せ・内容列は左寄せ）、SPは縦フロー。roleMap 未設定の業種だけが使う */
  flowHeader: [string, string];
  flow: FlowRow[];
  emphasisBlock: Paragraph;
  closing: Paragraph;
  emphasis: string[];
}

/**
 * 工程フロー図の1コマ。導入前と導入後を**同じ数だけ**並べ、同じ工程が縦に揃うようにする。
 *
 * kind:
 *  normal    = 通常
 *  auto      = AIへ移る工程。導入後の段では**連続するぶんをまとめて1つのグレー枠**に描く
 *              （導入前の段では「これから人の手を離れる工程」として mute で描く）
 *  highlight = 差し色で強調（1コマだけ。人が判断するところ）
 *  positive  = 導入後に良くなったコマ。差し色の罫線＋`badge` で見せる
 *
 * **✕・◯は使わない**（2026-08-06 なおき第4レビュー。何を言っているか分からないため）。
 * 変化は導入後側だけで見せる。
 */
export interface FlowNode {
  label?: string;
  /** コマの右上に出す短いバッジ（例「自動」）。positive のコマに付ける */
  badge?: string;
  kind: "normal" | "auto" | "highlight" | "positive";
}

